export type NavItemStatus = 'active' | 'soon'

export type NavLeaf = {
  id: string
  labelKey: MessageKey
  icon: NavIconName
  status: NavItemStatus
  to?: string
  end?: boolean
  /** Legacy role gate. Ignored when `permissions` is set. */
  roles?: readonly string[]
  /** Visible when the session holds at least one of these permissions (UX only). */
  permissions?: readonly string[]
  breadcrumbKey?: MessageKey
}

export type NavGroup = {
  id: string
  labelKey: MessageKey
  icon: NavIconName
  items: readonly NavLeaf[]
}

export type NavEntry =
  | { type: 'link'; item: NavLeaf }
  | { type: 'group'; group: NavGroup }

